    def check_event_rules(self, event_type, shensha_list):
        """
        检查特定事项的择日宜忌
        """
        if event_type not in self.EVENT_RULES:
            return {'宜': [], '忌': [], 'score': 0}
        
        rules = self.EVENT_RULES[event_type]
        yi_list = []
        ji_list = []
        score = 0
        
        # 检查吉神
        for shensha in shensha_list:
            name = shensha if isinstance(shensha, str) else shensha.get('name', '')
            if name in rules['宜']:
                yi_list.append(name)
                if name in self.JISHEN:
                    score += self.JISHEN[name][1]
        
        # 检查凶神
        for shensha in shensha_list:
            name = shensha if isinstance(shensha, str) else shensha.get('name', '')
            if name in rules['忌']:
                ji_list.append(name)
                if name in self.XIONGSHEN:
                    score += self.XIONGSHEN[name][1]
        
        return {
            'event_type': event_type,
            '宜': yi_list,
            '忌': ji_list,
            'score': score,
            'hege': len(ji_list) == 0
        }
    
