        gan_ke = {'甲': '戊', '乙': '己', '丙': '庚', '丁': '辛', 
                  '戊': '壬', '己': '癸', '庚': '甲', '辛': '乙',
                  '壬': '丙', '癸': '丁'}
        
        for i, zhi in enumerate(zhis):
            if zhi and ming_zhi and chong_pairs.get(zhi) == ming_zhi:
                gan = [sizhu.get('year_gan', ''), sizhu.get('month_gan', ''), 
                       sizhu.get('day_gan', ''), sizhu.get('hour_gan', '')][i]
                if gan and ming_gan and gan_ke.get(gan) == ming_gan:
                    result['格局'].append('天克地冲')
                    result['score'] -= 50
                    result['reason'].append(f'{["年", "月", "日", "时"][i]}柱天克地冲年命')
                    result['hege'] = False
                else:
                    result['格局'].append('地冲')
                    result['score'] -= 20
                    result['reason'].append(f'{["年", "月", "日", "时"][i]}柱地冲年命')
        
        # 检查合官合财
        if ming_gan:
            # 合财：我克者为财
            cai_gans = [k for k, v in gan_ke.items() if v == ming_gan]
            for cai in cai_gans:
                if cai in [sizhu.get('year_gan', ''), sizhu.get('month_gan', ''),
                           sizhu.get('day_gan', ''), sizhu.get('hour_gan', '')]:
                    result['格局'].append('合财格')
                    result['score'] += 15
                    result['reason'].append(f'见财星{cai}')
        
        # 检查比肩
        if ming_gan and ming_gan in [sizhu.get('year_gan', ''), sizhu.get('month_gan', ''),
                                     sizhu.get('day_gan', ''), sizhu.get('hour_gan', '')]:
            result['格局'].append('比肩格')
            result['score'] += 10
            result['reason'].append(f'见比肩{ming_gan}')
        
        # 检查长生
        _, changsheng = self.get_tiangan_changsheng(ming_gan)
        if changsheng and changsheng['长生'] in zhis:
            result['格局'].append('长生格')
            result['score'] += 15
            result['reason'].append(f'年命{ming_gan}长生在{changsheng["长生"]}')
        
        if changsheng and changsheng['旺'] in zhis:
            result['格局'].append('帝旺格')
            result['score'] += 12
            result['reason'].append(f'年命{ming_gan}帝旺在{changsheng["旺"]}')
        
        return result
    
