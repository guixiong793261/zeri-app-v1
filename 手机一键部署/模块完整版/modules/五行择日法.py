    # ========== 开业择日星曜推算 ==========
    
    def get_shengqi_ri(self, year_zhi, month_zhi, day_zhi):
        """
        生气星推算方法：
        子年子月——见戌日为生气
        丑年丑月——见亥日为生气
        寅年寅月——见子日为生气
        ...依次类推，每月见月支前两位地支为生气
        """
        zh_order = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥']
        
        # 生气日为月支的前两位（子->戌, 丑->亥, 寅->子...）
        if month_zhi in zh_order:
            idx = zh_order.index(month_zhi)
            shengqi_idx = (idx - 2) % 12
            shengqi_zhi = zh_order[shengqi_idx]
            return day_zhi == shengqi_zhi
        return False
    
    def get_tianfu_ri(self, year_zhi, month_zhi, day_zhi):
        """
        天富星推算方法：
        子年子月——见寅日为天富星
        丑年丑月——见卯日为天富星
        ...依次类推，每月见当月地支后第二位
        """
        zh_order = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥']
        
        if month_zhi in zh_order:
            idx = zh_order.index(month_zhi)
            tianfu_idx = (idx + 2) % 12
            tianfu_zhi = zh_order[tianfu_idx]
            return day_zhi == tianfu_zhi
        return False
    
    def get_jifu_ri(self, year_zhi, month_zhi, day_zhi):
        """
        极富星推算方法：
        子年子月——见辰日极富星
        丑年丑月——见巳日
        ...依次类推，每月见当月地支后第四位
        """
        zh_order = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥']
        
        if month_zhi in zh_order:
            idx = zh_order.index(month_zhi)
            jifu_idx = (idx + 4) % 12
            jifu_zhi = zh_order[jifu_idx]
            return day_zhi == jifu_zhi
        return False
    
