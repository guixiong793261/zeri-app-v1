    # ========== 择年法 ==========
    
    def get_taisui_fang(self, year_zhi):
        """
        获取太岁方
        太岁方：年地支所在方位，忌修造等大事
        太岁可坐不可向
        """
        return year_zhi
    
    def get_qisha_fang(self, year_zhi):
        """
        获取七煞方（岁破方）
        七煞方：年地支相冲的方位
        """
        chong_map = {
            '子': '午', '丑': '未', '寅': '申', '卯': '酉',
            '辰': '戌', '巳': '亥', '午': '子', '未': '丑',
            '申': '寅', '酉': '卯', '戌': '辰', '亥': '巳'
        }
        return chong_map.get(year_zhi)
    
    def analyze_year(self, year_zhi, shan_xiang=None):
        """
        分析年份吉凶
        """
        result = {
            'year_zhi': year_zhi,
            'taisui_fang': self.get_taisui_fang(year_zhi),
            'qisha_fang': self.get_qisha_fang(year_zhi),
            'suitable': True,
            'reasons': []
        }
        
        # 检查山向与太岁、七煞的关系
        if shan_xiang:
            zuoshan = shan_xiang[0] if shan_xiang else ''
            
            if zuoshan == result['taisui_fang']:
                result['reasons'].append(f'坐山{zuoshan}与太岁{year_zhi}相同，可坐不可向')
            elif zuoshan == result['qisha_fang']:
                result['reasons'].append(f'坐山{zuoshan}犯七煞方{result["qisha_fang"]}，大事应注意少用')
                result['suitable'] = False
        
        return result
    
    # ========== 择月法 ==========
    
    def get_shanxiang_wuxing(self, shan_xiang):
        """
        获取山向五行
        """
        if not shan_xiang:
            return None
        
        # 提取坐山
        zuoshan = None
        if '山' in shan_xiang:
            zuoshan = shan_xiang.split('山')[0]
        else:
            zuoshan = shan_xiang[0]
        
        return self.SHANXIANG_WUXING.get(zuoshan)
    
    def get_jiyue_by_wuxing(self, wuxing):
        """
        根据五行获取吉月
        """
        if wuxing not in self.WUXING_YUEFEN:
            return [], []
        
        primary = self.WUXING_YUEFEN[wuxing]
        secondary = self.WUXING_YUEFEN_SECONDARY.get(wuxing, [])
        
        return primary, secondary
    
    def analyze_month(self, year, month, shan_xiang):
        """
        分析月份吉凶
        """
        wuxing = self.get_shanxiang_wuxing(shan_xiang)
        
        result = {
            'year': year,
            'month': month,
            'shan_xiang': shan_xiang,
            'shan_wuxing': wuxing,
            'primary_months': [],
            'secondary_months': [],
            'month_type': '普通',
            'reasons': []
        }
        
        if wuxing:
            primary, secondary = self.get_jiyue_by_wuxing(wuxing)
            result['primary_months'] = primary
            result['secondary_months'] = secondary
            
            # 判断当前月份类型
            month_zhi = DI_ZHI[(month - 1) % 12]
            if month_zhi in primary:
                result['month_type'] = '优先'
                result['reasons'].append(f'{wuxing}山优先选用月份')
            elif month_zhi in secondary:
                result['month_type'] = '可用'
                result['reasons'].append(f'{wuxing}山可用月份')
            else:
                result['reasons'].append(f'{wuxing}山非优选月份')
        
        return result
    
    # ========== 择日法 ==========
    
    def analyze_rizu(self, sizhu, shan_xiang=None, owners=None):
        """
        分析日课四柱八字组合
        """
        result = {
            'sizhu': sizhu,
            '格局': [],
            'score': 0,
            'reasons': [],
            'hege': True
        }
        
        year_gan, year_zhi = sizhu.get('year_gan', ''), sizhu.get('year_zhi', '')
        month_gan, month_zhi = sizhu.get('month_gan', ''), sizhu.get('month_zhi', '')
        day_gan, day_zhi = sizhu.get('day_gan', ''), sizhu.get('day_zhi', '')
        hour_gan, hour_zhi = sizhu.get('hour_gan', ''), sizhu.get('hour_zhi', '')
        
        # 检查三合局
        zhis = [year_zhi, month_zhi, day_zhi, hour_zhi]
        for sanhe in self.SANHE:
            present = [z for z in zhis if z in sanhe]
            if len(present) >= 2:
                result['格局'].append(f'三合{self._get_sanhe_name(sanhe)}')
                result['score'] += 20
                result['reasons'].append(f'日课形成{self._get_sanhe_name(sanhe)}')
        
        # 检查三会局
        for sanhui in self.SANHUI:
            present = [z for z in zhis if z in sanhui]
            if len(present) >= 2:
                result['格局'].append(f'三会{self._get_sanhui_name(sanhui)}')
                result['score'] += 15
                result['reasons'].append(f'日课形成{self._get_sanhui_name(sanhui)}')
        
        # 检查六合
        if self.LIUHE.get(day_zhi) in zhis:
            result['格局'].append('日支六合')
            result['score'] += 10
            result['reasons'].append('日支与其他地支六合')
        
        # 检查十二长生
        if day_gan:
            changsheng_info = self._check_changsheng(day_gan, month_zhi)
            if changsheng_info:
                result['格局'].append(changsheng_info)
                if '长生' in changsheng_info or '帝旺' in changsheng_info:
                    result['score'] += 15
                    result['reasons'].append(f'日主得令：{changsheng_info}')
                elif '死' in changsheng_info or '绝' in changsheng_info:
                    result['score'] -= 10
                    result['reasons'].append(f'日主失令：{changsheng_info}')
        
        # 扶山判断
        if shan_xiang:
            fushan_result = self._check_fushan(sizhu, shan_xiang)
            if fushan_result:
                result['reasons'].append(fushan_result)
                if '生扶' in fushan_result:
                    result['score'] += 10
                elif '克制' in fushan_result:
                    result['score'] -= 15
                    result['hege'] = False
        
        # 相主判断
        if owners:
            xiangzhu_result = self._check_xiangzhu(sizhu, owners)
            if xiangzhu_result:
                result['reasons'].extend(xiangzhu_result)
        
        return result
    
    def _get_sanhe_name(self, sanhe):
        """获取三合局名称"""
        if '申' in sanhe:
            return '水局'
        elif '寅' in sanhe:
            return '火局'
        elif '巳' in sanhe:
            return '金局'
        elif '亥' in sanhe:
            return '木局'
        return '局'
    
    def _get_sanhui_name(self, sanhui):
        """获取三会局名称"""
        if '子' in sanhui:
            return '北方水'
        elif '卯' in sanhui:
            return '东方木'
        elif '午' in sanhui:
            return '南方火'
        elif '酉' in sanhui:
            return '西方金'
        return ''
    
    def _check_changsheng(self, day_gan, month_zhi):
        """检查日主十二长生状态"""
        if day_gan not in self.SHIER_CHANGSHENG:
            return None
        
        changsheng_list = self.SHIER_CHANGSHENG[day_gan]
        if month_zhi in changsheng_list:
            idx = changsheng_list.index(month_zhi)
            return self.CHANGSHENG_NAMES[idx]
        return None
    
    def _check_fushan(self, sizhu, shan_xiang):
        """扶山判断"""
        wuxing = self.get_shanxiang_wuxing(shan_xiang)
        if not wuxing:
            return None
        
        day_zhi = sizhu.get('day_zhi', '')
        month_zhi = sizhu.get('month_zhi', '')
        
        # 五行相生相克
        sheng = {'木': '火', '火': '土', '土': '金', '金': '水', '水': '木'}
        ke = {'木': '土', '土': '水', '水': '火', '火': '金', '金': '木'}
        zhi_wuxing = {
            '子': '水', '丑': '土', '寅': '木', '卯': '木',
            '辰': '土', '巳': '火', '午': '火', '未': '土',
            '申': '金', '酉': '金', '戌': '土', '亥': '水'
        }
        
        for zhi in [day_zhi, month_zhi]:
            if not zhi:
                continue
            zhi_wx = zhi_wuxing.get(zhi)
            if zhi_wx:
                if sheng.get(zhi_wx) == wuxing:
                    return f'{shan_xiang}山得{zhi}生扶'
                if ke.get(zhi_wx) == wuxing:
                    return f'{shan_xiang}山被{zhi}克制'
        
        return None
    
    def _check_xiangzhu(self, sizhu, owners):
        """相主判断"""
        reasons = []
        day_zhi = sizhu.get('day_zhi', '')
        chong_map = {
            '子': '午', '丑': '未', '寅': '申', '卯': '酉',
            '辰': '戌', '巳': '亥', '午': '子', '未': '丑',
            '申': '寅', '酉': '卯', '戌': '辰', '亥': '巳'
        }
        
        for owner in owners:
            name = owner.get('name', '事主')
            shengxiao = owner.get('生肖', '')
            zhi_map = {'鼠':'子','牛':'丑','虎':'寅','兔':'卯','龙':'辰','蛇':'巳',
                       '马':'午','羊':'未','猴':'申','鸡':'酉','狗':'戌','猪':'亥'}
            owner_zhi = zhi_map.get(shengxiao, '')
            
            if owner_zhi and chong_map.get(owner_zhi) == day_zhi:
                reasons.append(f'日支与{name}生肖相冲')
        
        return reasons
    
    # ========== 择时法 ==========
    
    def analyze_shichen(self, sizhu):
        """
        分析时辰吉凶
        """
        day_zhi = sizhu.get('day_zhi', '')
        hour_zhi = sizhu.get('hour_zhi', '')
        
        result = {
            'day_zhi': day_zhi,
            'hour_zhi': hour_zhi,
            'suitable': True,
            'reasons': [],
            'score': 0
        }
        
        if not day_zhi or not hour_zhi:
            return result
        
        # 检查六合
        if self.LIUHE.get(day_zhi) == hour_zhi:
            result['reasons'].append('日时六合')
            result['score'] += 10
        
        # 检查三合
        for sanhe in self.SANHE:
            if day_zhi in sanhe and hour_zhi in sanhe:
                result['reasons'].append(f'日时三合{self._get_sanhe_name(sanhe)}')
                result['score'] += 15
        
        # 检查三会
        for sanhui in self.SANHUI:
            if day_zhi in sanhui and hour_zhi in sanhui:
                result['reasons'].append(f'日时三会{self._get_sanhui_name(sanhui)}')
                result['score'] += 12
        
