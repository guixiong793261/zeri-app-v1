    def check_sansha(self, zhi, shan):
        """
        判断年/月支是否犯三煞
        
        申子辰年/月三煞在巳、丙、午、丁、未山；
        寅午戌年/月三煞在亥、壬、子、癸、丑山；
        亥卯未年/月三煞在申、庚、酉、辛、戌山；
        巳酉丑年/月三煞在寅、甲、卯、乙、辰山。
        """
        for sanhe, shans in self.SAN_SHA.items():
            if zhi in sanhe and shan in shans:
                return True, sanhe
        return False, None
    
    def get_tiangan_changsheng(self, gan):
        """
        获取天干长生信息
        
        阳干顺推：甲丙戊庚壬
        阴干逆寻：乙丁己辛癸
        """
        if gan in self.TIAN_GAN_CHANGSHENG_YANG:
            return '阳', self.TIAN_GAN_CHANGSHENG_YANG[gan]
        elif gan in self.TIAN_GAN_CHANGSHENG_YIN:
            return '阴', self.TIAN_GAN_CHANGSHENG_YIN[gan]
        return None, None
    
    def check_nianming_zhensha(self, nianming_zhi, day_zhi):
        """
        判断年命真三煞
        
        申子辰命，真煞在未；
        亥卯未命，真煞在戌；
        寅午戌命，真煞在丑；
        巳酉丑命，真煞在辰。
        """
        for sanhe, sha in self.NIAN_MING_ZHEN_SHA.items():
            if nianming_zhi in sanhe and day_zhi == sha:
                return True, sanhe
        return False, None
    
    def check_zhen_yinfu(self, sizhu, zuoshan):
        """
        判断正阴府
        
        甲已二干艮巽凶，乙庚乾兑祸重重；
        丙辛坤坎君莫犯，丁壬离乾主无宗；
        戊癸震坤为大杀，正阴府歌记心中。
        """
        all_gans = [sizhu.get('year_gan', ''), sizhu.get('month_gan', ''), 
                    sizhu.get('day_gan', ''), sizhu.get('hour_gan', '')]
        
        for hehua, shans in self.ZHENG_YIN_FU.items():
            # 检查是否有合化干
            has_hehua = any(g in hehua for g in all_gans if g)
            if has_hehua and zuoshan in shans:
                return True, hehua, shans
        return False, None, None
    
