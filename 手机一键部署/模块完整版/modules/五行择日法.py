    # ========== 四大局判断 ==========
    
    def analyze_sida_ju(self, sizhu, shan_xiang):
        """
        四大局判断：生局、旺局、财局、杀局、泄局
        
        坐山为我，日课五行为客：
        - 生局：日课五行生我（客生主）
        - 旺局：日课五行比和（客主比和）
        - 财局：我克日课五行（主克客）- 需坐山当令
        - 杀局：日课五行克我（客克主）- 大凶
        - 泄局：我生日课五行（主生客）- 大凶
        """
        zuoshan = shan_xiang[0] if shan_xiang else ''
        shan_wuxing = self.SHAN_WUXING.get(zuoshan)
        
        if not shan_wuxing:
            return {'局': '未知', 'score': 0, 'reason': '无法确定坐山五行'}
        
        # 五行相生相克
        sheng = {'木': '火', '火': '土', '土': '金', '金': '水', '水': '木'}  # 生
        ke = {'木': '土', '土': '水', '水': '火', '火': '金', '金': '木'}    # 克
        zhi_wuxing = {
            '子': '水', '丑': '土', '寅': '木', '卯': '木',
            '辰': '土', '巳': '火', '午': '火', '未': '土',
            '申': '金', '酉': '金', '戌': '土', '亥': '水'
        }
        
        # 统计日课地支五行
        day_zhi = sizhu.get('day_zhi', '')
        month_zhi = sizhu.get('month_zhi', '')
        hour_zhi = sizhu.get('hour_zhi', '')
        
        wuxing_counts = {'木': 0, '火': 0, '土': 0, '金': 0, '水': 0}
        
        for zhi in [day_zhi, month_zhi, hour_zhi]:
            if zhi:
                wx = zhi_wuxing.get(zhi)
                if wx:
                    wuxing_counts[wx] += 1
        
        # 判断四大局
        max_wx = max(wuxing_counts, key=wuxing_counts.get)
        max_count = wuxing_counts[max_wx]
        
        # 检查三合局
        sanhe_jv = self._check_sanhe_ju([day_zhi, month_zhi, hour_zhi])
        
        result = {
            '坐山': zuoshan,
            '坐山五行': shan_wuxing,
            '日课主要五行': max_wx,
            '五行分布': wuxing_counts,
            '三合局': sanhe_jv,
            '局': '',
            'score': 0,
            'reason': '',
            'hege': True
        }
        
        if sanhe_jv:
            # 三合局优先判断
            ju_wx = self._get_sanhe_wuxing(sanhe_jv)
            if ju_wx:
                if sheng.get(ju_wx) == shan_wuxing:
                    result['局'] = '生局(三合)'
                    result['score'] = 30
                    result['reason'] = f'{sanhe_jv}生{zuoshan}山'
                elif ju_wx == shan_wuxing:
                    result['局'] = '旺局(三合)'
                    result['score'] = 25
                    result['reason'] = f'{sanhe_jv}与{zuoshan}山比和'
                elif ke.get(shan_wuxing) == ju_wx:
                    # 财局需判断是否当令
                    is_dangling = self._is_shan_dangling(shan_wuxing, month_zhi)
                    if is_dangling:
                        result['局'] = '财局(三合)'
                        result['score'] = 15
                        result['reason'] = f'{zuoshan}山克{sanhe_jv}，坐山当令可用'
                    else:
                        result['局'] = '财局(不当令)'
                        result['score'] = -5
                        result['reason'] = f'{zuoshan}山克{sanhe_jv}，坐山不当令慎用'
                elif ke.get(ju_wx) == shan_wuxing:
                    result['局'] = '杀局(三合)'
                    result['score'] = -30
                    result['reason'] = f'{sanhe_jv}克{zuoshan}山，大凶'
                    result['hege'] = False
                elif sheng.get(shan_wuxing) == ju_wx:
                    result['局'] = '泄局(三合)'
                    result['score'] = -25
                    result['reason'] = f'{zuoshan}山生{sanhe_jv}，大凶'
                    result['hege'] = False
        else:
            # 非三合局判断
            if max_count >= 2:  # 至少两个地支同五行
                if sheng.get(max_wx) == shan_wuxing:
                    result['局'] = '生局'
                    result['score'] = 25
                    result['reason'] = f'{max_wx}生{shan_wuxing}'
                elif max_wx == shan_wuxing:
                    result['局'] = '旺局'
                    result['score'] = 20
                    result['reason'] = f'{max_wx}与{shan_wuxing}比和'
                elif ke.get(shan_wuxing) == max_wx:
                    is_dangling = self._is_shan_dangling(shan_wuxing, month_zhi)
                    if is_dangling:
                        result['局'] = '财局'
                        result['score'] = 10
                        result['reason'] = f'{shan_wuxing}克{max_wx}，坐山当令可用'
                    else:
                        result['局'] = '财局(不当令)'
                        result['score'] = -10
