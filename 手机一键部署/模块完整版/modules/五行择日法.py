    def check_shanfang_sha(self, zuoshan, day_ganzhi, hour_ganzhi):
        """
        判断山方煞（先后天煞）
        
        zuoshan: 坐山（八卦：坎、艮、震、巽、离、坤、兑、乾）
        day_ganzhi: 日干支（如'乙卯'）
        hour_ganzhi: 时干支（如'乙卯'）
        """
        sha_info = self.SHAN_FANG_SHA.get(zuoshan)
        if not sha_info:
            return {'忌日': False, '忌时': False, 'reason': ''}
        
        day_j = day_ganzhi in sha_info['忌日']
        hour_j = hour_ganzhi in sha_info['忌时']
        
        reasons = []
        if day_j:
            reasons.append(f'{zuoshan}山忌{day_ganzhi}日')
        if hour_j:
            reasons.append(f'{zuoshan}山忌{hour_ganzhi}时')
        
        return {
            '忌日': day_j,
            '忌时': hour_j,
            'reason': '; '.join(reasons)
        }
    
    def check_chongding_sha(self, zuoshan, jianxiang, day_ganzhi, hour_ganzhi):
        """
        判断冲丁煞（分金煞）
        
        zuoshan: 坐山
        jianxiang: 兼向（如'兼亥'、'兼子'）
        day_ganzhi: 日干支
        hour_ganzhi: 时干支
        """
        sha_info = self.CHONG_DING_SHA.get(zuoshan)
        if not sha_info:
            return {'分金': '', '忌日': False, '忌时': False, 'reason': ''}
        
        jian_info = sha_info.get(jianxiang)
        if not jian_info:
            return {'分金': '', '忌日': False, '忌时': False, 'reason': ''}
        
        ji_list = jian_info['忌']
        day_j = day_ganzhi in ji_list
        hour_j = hour_ganzhi in ji_list
        
        reasons = []
        if day_j:
            reasons.append(f'{zuoshan}{jianxiang}用{jian_info["分金"]}分金，忌{day_ganzhi}日')
        if hour_j:
            reasons.append(f'{zuoshan}{jianxiang}用{jian_info["分金"]}分金，忌{hour_ganzhi}时')
        
        return {
            '分金': jian_info['分金'],
            '忌日': day_j,
            '忌时': hour_j,
            'reason': '; '.join(reasons)
        }
    
    def analyze_bulong(self, zuoshan, sizhu):
        """
        补龙分析
        
        根据坐山判断补龙吉凶局
        """
        # 简化的补龙判断
        shan_wuxing = self.SHAN_WUXING.get(zuoshan)
        if not shan_wuxing:
            return {'局': '未知', 'score': 0, 'reason': '无法确定坐山五行'}
        
        day_zhi = sizhu.get('day_zhi', '')
        month_zhi = sizhu.get('month_zhi', '')
        hour_zhi = sizhu.get('hour_zhi', '')
        
        # 检查是否构成三合局
        sanhe_jv = self._check_sanhe_ju([day_zhi, month_zhi, hour_zhi])
        
        wuxing_map = {'水局': '水', '火局': '火', '金局': '金', '木局': '木'}
        ju_wx = wuxing_map.get(sanhe_jv) if sanhe_jv else None
        
        result = {
            '坐山': zuoshan,
            '坐山五行': shan_wuxing,
            '三合局': sanhe_jv,
            '局': '',
            'score': 0,
            'reason': '',
            'hege': True
        }
        
        sheng = {'木': '火', '火': '土', '土': '金', '金': '水', '水': '木'}
        ke = {'木': '土', '土': '水', '水': '火', '火': '金', '金': '木'}
        
        if sanhe_jv and ju_wx:
            if sheng.get(ju_wx) == shan_wuxing:
                result['局'] = '生局(补龙)'
                result['score'] = 25
                result['reason'] = f'{sanhe_jv}生{zuoshan}山'
            elif ju_wx == shan_wuxing:
                result['局'] = '旺局(补龙)'
                result['score'] = 20
                result['reason'] = f'{sanhe_jv}与{zuoshan}山比和'
            elif ke.get(shan_wuxing) == ju_wx:
                result['局'] = '财局(补龙)'
                result['score'] = 10
                result['reason'] = f'{zuoshan}山克{sanhe_jv}'
            elif ke.get(ju_wx) == shan_wuxing:
                result['局'] = '克煞局(补龙)'
                result['score'] = -30
                result['reason'] = f'{sanhe_jv}克{zuoshan}山，大凶'
                result['hege'] = False
            elif sheng.get(shan_wuxing) == ju_wx:
                result['局'] = '泄气局(补龙)'
                result['score'] = -20
                result['reason'] = f'{zuoshan}山生{sanhe_jv}，泄气'
                result['hege'] = False
        else:
            result['局'] = '普通'
            result['score'] = 5
            result['reason'] = '无明显补龙格局'
        
        return result
    
    def analyze_xiangzhu(self, nianming, sizhu):
        """
        相主分析
        
        nianming: 年命（如'甲子'）
        """
        if not nianming:
            return {'格局': '', 'score': 0, 'reason': '', 'hege': True}
        
        ming_gan = nianming[0] if len(nianming) > 0 else ''
        ming_zhi = nianming[1] if len(nianming) > 1 else ''
        
        all_ganzhi = [
            f"{sizhu.get('year_gan', '')}{sizhu.get('year_zhi', '')}",
            f"{sizhu.get('month_gan', '')}{sizhu.get('month_zhi', '')}",
            f"{sizhu.get('day_gan', '')}{sizhu.get('day_zhi', '')}",
            f"{sizhu.get('hour_gan', '')}{sizhu.get('hour_zhi', '')}"
        ]
        
        result = {
            '年命': nianming,
            '格局': [],
            'score': 0,
            'reason': [],
            'hege': True
        }
        
        # 检查是否有冲克
        zhis = [sizhu.get('year_zhi', ''), sizhu.get('month_zhi', ''), 
                sizhu.get('day_zhi', ''), sizhu.get('hour_zhi', '')]
        
