def get_mountain_data(mountain_name: str) -> dict:
    """
    获取指定山向的择吉数据
    
    Args:
        mountain_name: 山向名称，如"壬山丙向"、"子山午向"
        
    Returns:
        山向择吉数据字典，如果不存在返回空字典
    """
    return MOUNTAIN_DATA.get(mountain_name, {})


def get_yang_gong_jishi(gan_combination: str) -> list:
    """
    获取杨公风水立向择日大吉时
    
    Args:
        gan_combination: 天干组合，如"甲己"、"乙庚"等
        
    Returns:
        吉时列表
    """
    return YANG_GONG_JISHI.get(gan_combination, [])


def get_all_mountain_names() -> list:
    """
    获取所有支持的山向名称列表
    
    Returns:
        山向名称列表
    """
    return list(MOUNTAIN_DATA.keys())


def check_year_luck(mountain_name: str, year: str) -> str:
    """
    检查指定山向在指定年份的吉凶
    
    Args:
        mountain_name: 山向名称
        year: 年份，如"甲子"、"乙丑"等
        
    Returns:
        吉凶描述
    """
    data = get_mountain_data(mountain_name)
    if data:
        return data['yearly_luck'].get(year, '未知')
    return '未知'


def check_month_luck(mountain_name: str, month: str, bury: bool = False) -> dict:
    """
    检查指定山向在指定月份的吉凶
    
    Args:
        mountain_name: 山向名称
        month: 月份，如"正月"、"二月"等
        bury: 是否为安葬（True为安葬，False为建造）
        
    Returns:
        月份吉凶数据
    """
    data = get_mountain_data(mountain_name)
    if data:
        if bury:
            return data['bury_monthly_luck'].get(month, {})
        return data['monthly_luck'].get(month, {})
    return {}


def check_keshan(mountain_name: str, year_gan: str) -> dict:
    """
    检查克山运
    
    Args:
        mountain_name: 山向名称
        year_gan: 年干组合，如"甲己"、"乙庚"等
        
    Returns:
        克山运信息
    """
    data = get_mountain_data(mountain_name)
    if data and 'avoid_info' in data and 'keshan' in data['avoid_info']:
        # 尝试带"年"字的键
        key_with_year = f"{year_gan}年"
        return data['avoid_info']['keshan'].get(key_with_year, data['avoid_info']['keshan'].get(year_gan, {}))
    return {}


