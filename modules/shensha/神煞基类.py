    def _add_shensha(self, name, score, description):
        """
        添加神煞（异名归一到典载正名后按同名去重）

        2026-10 A6-3：异名双扣收口——同一神煞常以「正名」与「正名+日」两种名字在
        不同作用域/层级各注册一次（见模块级 _SHENSHA_ALIAS_KEY）。旧实现仅按字面
        同名去重，异名同日共现时各计一次分，造成双扣。此处先把异名归一到典载正名
        再走同名去重，从源头消除异名双扣；正名与其异名在单一分值表 SHENSHA_SCORES
        中取值完全相同，故分值口径不变。

        Args:
            name: 神煞名称
            score: 分数（默认值）
            description: 描述
        """
        # 2026-10 A6-3：异名归一到典载正名（往亡日→往亡、旺日→王日、母仓日→母仓…）
        name = _SHENSHA_ALIAS_KEY.get(name, name)
        # 去重检查
        existing_names = [s['name'] for s in self.shensha_list]
        if name not in existing_names:
            # 2026-09-16 口径统一：分值以 modules/事项标准.py 的 SHENSHA_SCORES
            # 单一表为准（按 self._std_event 规范事项取数）；表中未登记的神煞
            # （动态名如"三奇{xx}"、或同名但分值随上下文变化者）沿用调用处默认值，
            # 保证任何情况下评分行为不回退。
            try:
                from ..事项标准 import shensha_score as _shensha_score
                _resolved = _shensha_score(getattr(self, '_std_event', None), name, score)
                if _resolved is not None:
                    score = _resolved
            except Exception:
                pass
            # 2026-10-12 ③（§66 拍板方案A）：三煞家族神煞通道「识别展示，不计分」收口。
            # 年三煞(-18)/劫煞(-25)/灾煞(-25)/岁煞(-20) 的注册默认分与 SHENSHA_SCORES
            # 表值在解析层统一置 0：典据收口（B-b 轨一 §9.10/§9.12）判定两口径均无典据，
            # 且与评分器通道甲（三煞扣分体系 §63/§64）同日并存属双重计分（实测受影响日
            # 三笔并存 -18+-15+-30）。注册保留、命中照常识别展示（description 追加标注）；
            # 评分器通道甲、忌事通道（ji -15）原样不动，嫁娶路径本就仅展示不受影响。
            # SHENSHA_SCORES 表值按对账惯例不回改，实际分值以本收口为准。
            if name in ('年三煞', '劫煞', '灾煞', '岁煞'):
                score = 0
                if '（识别展示，不计分）' not in description:
                    description += '（识别展示，不计分）'
            self.shensha_list.append({
                'name': name,
                'score': score,
                'description': description
            })
    
