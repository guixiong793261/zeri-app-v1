    pos = get_sunmoon_jieqi_position(d)
    if pos is None:
        return '', ''
    sun = TAIYANG_DAOSHAN_24SHAN[pos - 1]
    moon = TAIYANG_DAOSHAN_24SHAN[(pos - 1 + 12) % 24]
    return sun, moon


