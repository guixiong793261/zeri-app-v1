def calc_liuyao(lunar_month, lunar_day, is_leap=False):
    """六曜：(农历月 + 农历日) mod 6 映射 LIUYAO 通书名序（与汉程黄历对齐）。
    余数：0大安 1赤口 2先胜 3友引 4先负 5佛灭
    lunar_month / lunar_day 可传入 int 或 str（如 '七'、'十六'），统一转成数字。"""
    try:
        # 支持字符串（中文）→ 数字（覆盖 get_lunar_date 返回中文月/日的情形）
        _CN_MONTH = {'正':1,'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10,'冬':11,'腊':12}
        _CN_DAY_UNIT = {'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10}
        def _to_int(x, which):
            if isinstance(x, int):
                return x
            s = str(x).strip()
            if s.isdigit():
                return int(s)
            if which == 'month':
                s2 = s.replace('月', '').replace('闰', '')
                if s2 in _CN_MONTH:
                    return _CN_MONTH[s2]
                if len(s2) == 2 and s2[0] in _CN_MONTH and s2[1] in _CN_MONTH:
                    # 不会出现七月这种；七月=七 → 统一在 unit 里处理
                    pass
                if s2 in _CN_DAY_UNIT:
                    # 一～十 月
                    return _CN_DAY_UNIT[s2]
            # 日：初X / XX / 中文 十～廿～三十
            def _parse_day(cn):
                cn = cn.replace('日', '')
                if cn.startswith('初') and len(cn) == 2 and cn[1] in _CN_DAY_UNIT:
                    return _CN_DAY_UNIT[cn[1]]
                if cn == '十一': return 11
                if cn == '十二': return 12
                if cn == '十三': return 13
                if cn == '十四': return 14
                if cn == '十五': return 15
                if cn == '十六': return 16
                if cn == '十七': return 17
                if cn == '十八': return 18
                if cn == '十九': return 19
                if cn.startswith('廿'):
                    if cn == '二十': return 20
                    if len(cn) == 2 and cn[1] in _CN_DAY_UNIT:
                        return 20 + _CN_DAY_UNIT[cn[1]]
                if cn.startswith('三十'): return 30
                if cn == '廿': return 20
                if cn == '卅': return 30
                return None
            r = _parse_day(s) if which == 'day' else None
            if r:
                return r
            # 最后兜底：若是中文数字（如七月=七=7）
            if s in _CN_DAY_UNIT:
                return _CN_DAY_UNIT[s]
            return None

        m_num = _to_int(lunar_month, 'month')
        d_num = _to_int(lunar_day, 'day')
        if not m_num or not d_num:
            return '未知', '—'
        # 闰月按下月计算（沿用当月）
        # 汉程六曜公式：idx = (农历月 + 农历日) % 6
        idx = (m_num + d_num) % 6
        name = LIUYAO[idx]
        return name, LIUYAO_JIXIONG[name]
    except Exception:
        return '未知', '—'


