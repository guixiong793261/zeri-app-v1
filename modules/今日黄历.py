def calc_shichen_jixiong(day_gan, day_zhi, nian_zhi, month_zhi):
    """计算当日12时辰吉凶（黄历通用版，不含坐山/主命）。"""
    results = []
    zi_gan = WUSHU_DUN.get(day_gan, '甲')
    zi_idx = TIAN_GAN_ORDER.index(zi_gan)
    for i, (zhi, hour_name) in enumerate(SHI_CHEN_LIST):
        hour_gan = TIAN_GAN_ORDER[(zi_idx + i) % 10]
        score = 0
        tags = []
        # 日破时
        if get_chong_zhi(day_zhi) == zhi:
            score -= 20
            tags.append('日破')
        # 五不遇时
        if is_wubuyu(hour_gan, day_gan):
            score -= 15
            tags.append('五不遇')
        # 贵人时
        if zhi in GUIREN_SHICHEN.get(day_gan, []):
            score += 15
            tags.append('贵人时')
        # 禄神时
        if zhi == LU_SHICHEN.get(day_gan):
            score += 10
            tags.append('禄神时')
        # 驿马时（按日支三合）
        ma = RI_MA.get(day_zhi)
        if zhi == ma:
            score += 10
            tags.append('驿马')
        # 大黄道
        dh, dhj = get_da_huangdao(day_zhi, zhi)
        if dhj == '吉':
            score += 10
            tags.append(f'大黄道·{dh}')
        elif dhj == '凶':
            score -= 10
            tags.append(f'黑道·{dh}')
        # 小黄道（建除时辰）
        xh = XIAO_HUANGDAO_BY_HOUR.get(zhi, '')
        if xh in XIAO_HUANGDAO_JI:
            score += 5
            tags.append(f'建除{xh}')
        elif xh in {'破', '危', '闭'}:
            score -= 5
            tags.append(f'建除{xh}')
        if not tags:
            tags.append('平')
        if score > 0:
            lvl = '吉'
        elif score < 0:
            lvl = '凶'
        else:
            lvl = '平'
        results.append({
            'name': hour_name,
            'zhi': zhi,
            'ganzhi': f'{hour_gan}{zhi}',
            'score': score,
            'level': lvl,
            'tags': tags,
        })
    return results


