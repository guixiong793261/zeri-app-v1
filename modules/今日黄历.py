def get_yi_ji(day_gan, day_zhi):
    """按六十甲子日柱查表，返回 (宜列表, 忌列表)。
    （与汉程黄历 / 通胜口径对齐，甲戌日即汉程通用版：沐浴理发会亲友塑绘开光栽种牧养嫁娶经络补垣塞穴
     忌开市入宅动土破土安葬作灶上梁安床开仓祈福）"""
    ganzhi = f"{day_gan}{day_zhi}"
    if ganzhi in YIJI_60:
        return list(YIJI_60[ganzhi][0]), list(YIJI_60[ganzhi][1])
    # 兜底：彭祖百忌提示的禁忌加进去
    ji = []
    peng = PENG_ZU.get(day_gan, "") + PENG_ZU.get(day_zhi, "")
    for kw, item in (("嫁娶","嫁娶"),("安床","安床"),("开仓","开仓"),("动土","动土"),
                     ("修造","修造"),("祭祀","祭祀")):
        if kw in peng:
            ji.append(item)
    return ["祭祀","会亲友","出行"], ji



