        result += "【说明】\n"
        result += "• 公历↔农历、月胎神按通书逐月胎神占（农历月），日胎神按六十甲子查询\n"
        result += "• 日禄（日干临官）、日马（日支三合驿马）、日破（日支六冲）为通书常见参数\n"
