def _instantiate(path, cls_name, package='modules', *args, **kwargs):
    """按 (虚线路径, 类名) 懒加载实例化；相对路径以 package 为包根。"""
    import importlib
    if path.startswith('.'):
        module = importlib.import_module(path, package=package)
    else:
        module = importlib.import_module(path)
    return getattr(module, cls_name)(*args, **kwargs)


def get_rule_checker(event_type):
    """规范/别名事项 → 规则检查器实例（与原 modules/rules/__init__.py 行为一致）。

    无专属规则文件的事项（入学/求医/签约及未知事项）→ GenericRuleChecker(event_type)
    """
    canonical = canonical_event(event_type)
    spec = RULE_CHECKER_CLASSES.get(canonical)
    if spec is None:
        return _instantiate(GENERIC_RULE_CLASS[0], GENERIC_RULE_CLASS[1],
                            'modules', event_type)
    # GenericRuleChecker 需要 event_type 入参；其余检查器无构造参数
    return _instantiate(spec[0], spec[1], 'modules')


def get_shensha_checker(event_type):
    """规范/别名事项 → 常规神煞检查器实例（与原 modules/shensha/__init__.py 一致）。

    注意：修造类在评分器中另有 ConstructionShenShaCheckerExt 分支
    （需 zuoshan/zhuming/direction 参数），不在此函数处理。
    """
    canonical = canonical_event(event_type)
    spec = SHENSHA_CHECKER_CLASSES.get(canonical)
    if spec is None:
        checker = _instantiate(GENERIC_SHENSHA_CLASS[0], GENERIC_SHENSHA_CLASS[1], 'modules')
        # P2 部分匹配拆分（2026-10-18，001 §123）：通用检查器同样打 _std_event 戳。
