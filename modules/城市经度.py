# ---- 派生结构 ----
CITY_LONGITUDE = {city: lng for _prov, cities in PROVINCE_CITIES for city, lng in cities}
_CITY_PROVINCE = {city: prov for prov, cities in PROVINCE_CITIES for city, _ in cities}
CITY_NAMES = [city for _prov, cities in PROVINCE_CITIES for city, _ in cities]


def get_longitude(city):
    """城市名 → 经度 float；未知/空 → None。"""
    if city is None:
        return None
    return CITY_LONGITUDE.get(str(city).strip())


def province_of(city):
    """城市名 → 所属省/区；未知 → None。"""
    if city is None:
        return None
    return _CITY_PROVINCE.get(str(city).strip())


def filter_cities(keyword, limit=100):
    """按关键词过滤城市（子串包含，保持显示顺序）；空词 → 前 limit 个。"""
    kw = str(keyword or '').strip()
    if not kw:
        return CITY_NAMES[:limit]
    return [c for c in CITY_NAMES if kw in c][:limit]


# ---- 导入自检：城市名唯一、经度在有效域（重复名必须消歧后才能入库）----
_dups = {c for c in CITY_NAMES if CITY_NAMES.count(c) > 1}
if _dups:
    raise ValueError(f'城市经度库存在重名城市，需消歧: {sorted(_dups)}')
_bad = {c: v for c, v in CITY_LONGITUDE.items() if not (60.0 <= v <= 150.0)}
if _bad:
    raise ValueError(f'城市经度越出 [60,150] 有效域: {_bad}')
